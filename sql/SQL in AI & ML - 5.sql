-- Product Sale summary - For every product what is statistics summary
select
  ProductID,
  count(*) as Total_orders,
  sum(Total) as total_sales,
  avg(SellingPrice) as avg_sales,
  min(Total) as min_sales,
  max(Total) as max_sales
from `e1.order_items`
group by ProductID

