--The Finance team wants a summary of all the transaction
select
  count(*) as no_of_payment,
  sum(amount) as total_payment_amount,
  avg(amount) as avg_payment,
  min(amount) as min_payment,
  max(amount) as max_payment
from `e1.payments`

