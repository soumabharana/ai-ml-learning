-- Calculate total sales value for every order.
select *
from `e1.order_items`
limit 5

select
  OrderID,
  sum(Total) as total_value
from `e1.order_items`
group by OrderID
order by OrderID

select
  o.OrderID,
  sum(oi.Total) as total_sales
from `e1.orders` as o
inner join `e1.order_items` as oi
on o.OrderID = oi.OrderID
group by o.OrderID
order by OrderID

