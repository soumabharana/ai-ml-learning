from `e1.products`
limit 5


select *
from `e1.categories`
limit 5

alter table `e1.categories`
rename column string_field_0 to CategoryID

alter table `e1.categories`
rename column string_field_1 to CategoryName

select
  p.ProductID,
  p.ProductName,
  c.CategoryID,
  c.CategoryName
from `e1.categories` as c
join `e1.products` as p
on c.categoryID = p.categoryID


--Display products belonging to the Electronics category.
select
  p.ProductID,
  p.ProductName,
  c.CategoryID,
  c.CategoryName
from `e1.categories` as c
join `e1.products` as p
on c.categoryID = p.categoryID
where c.CategoryName = "Electronics"



--Display products with their category names, sorted by MRP from highest to lowest.
select
  p.ProductID,
  p.ProductName,
  c.CategoryID,
  c.CategoryName,
  MRP
from `e1.categories` as c
join `e1.products` as p
on c.categoryID = p.categoryID
order by MRP desc

-- Display ProductName, CategoryName and discount amount.

select
  p.ProductID,
  p.ProductName,
  c.CategoryID,
  c.CategoryName,
  p.MRP - p.SellingPrice as discount_amt
from `e1.categories` as c
inner join `e1.products` as p
on c.CategoryID = p.CategoryID


